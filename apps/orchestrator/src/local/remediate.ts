import type { RemediationBundleArgs } from "@contextpane/catalog";
import type { CorrelationContext } from "../mcp/context.ts";

/**
 * Deterministic remediation templates. These are what Tier 3 falls back to
 * when no Meta API key is present, and the reference the muse-code output is
 * compared against structurally (same cmdlets, same entities).
 */

function psString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

export function buildPowerShellRemediation(ctx: CorrelationContext): string {
  const lic = ctx.license.data;
  const drifted = lic.driftedUsers;
  const blocking = ctx.policies.data.find((p) => p.blocks) ?? ctx.policies.data[0];
  const ticket = ctx.erp.ticket.ticketId;
  const tenant = ctx.erp.tenant;
  const lines: string[] = [];
  lines.push("#Requires -Version 7.0");
  lines.push("#Requires -Modules Microsoft.Graph.Users, Microsoft.Graph.Identity.SignIns");
  lines.push("<#");
  lines.push(`.SYNOPSIS`);
  lines.push(`    ContextPane remediation for ${ticket} — ${tenant.displayName}`);
  lines.push(`.DESCRIPTION`);
  lines.push(`    1. Assign ${lic.sku.skuPartNumber} (${lic.sku.skuName}) to ${drifted.length} drifted member(s) of ${lic.group.displayName}`);
  lines.push(`       and remove the legacy ${lic.sku.legacySkuPartNumber} plan.`);
  if (blocking) {
    lines.push(`    2. Exclude ${lic.group.displayName} from Conditional Access policy '${blocking.displayName}'`);
    lines.push(`       and switch it to report-only so the block is observable but no longer enforced.`);
  }
  lines.push(`    Generated by ContextPane Tier 3 for human approval. Supports -WhatIf.`);
  lines.push("#>");
  lines.push("[CmdletBinding(SupportsShouldProcess)]");
  lines.push("param(");
  lines.push(`    [string]$TenantId = ${psString(tenant.entraTenantId)},`);
  lines.push(`    [string]$TargetSkuPartNumber = ${psString(lic.sku.skuPartNumber)},`);
  lines.push(`    [string]$LegacySkuPartNumber = ${psString(lic.sku.legacySkuPartNumber)},`);
  lines.push(`    [string]$EntitlementGroupName = ${psString(lic.group.displayName)},`);
  if (blocking) lines.push(`    [string]$PolicyDisplayName = ${psString(blocking.displayName)},`);
  lines.push("    [string[]]$DriftedUpns = @(");
  drifted.forEach((u, i) => lines.push(`        ${psString(u.upn)}${i < drifted.length - 1 ? "," : ""}`));
  lines.push("    )");
  lines.push(")");
  lines.push("");
  lines.push("$ErrorActionPreference = 'Stop'");
  lines.push("");
  lines.push("$ctx = Get-MgContext");
  lines.push("if (-not $ctx) { throw 'No Microsoft Graph context. Run Connect-MgGraph -Scopes User.ReadWrite.All,Organization.Read.All,Policy.ReadWrite.ConditionalAccess,Group.Read.All' }");
  lines.push("if ($ctx.TenantId -ne $TenantId) { throw \"Connected to tenant $($ctx.TenantId), expected $TenantId\" }");
  lines.push("");
  lines.push("# --- 1. License remediation (Set-MgUserLicense) --------------------------------");
  lines.push("$skus = Get-MgSubscribedSku -All");
  lines.push("$targetSku = $skus | Where-Object SkuPartNumber -eq $TargetSkuPartNumber | Select-Object -First 1");
  lines.push("$legacySku = $skus | Where-Object SkuPartNumber -eq $LegacySkuPartNumber | Select-Object -First 1");
  lines.push("if (-not $targetSku) { throw \"SKU $TargetSkuPartNumber is not available in tenant $TenantId\" }");
  lines.push("$available = $targetSku.PrepaidUnits.Enabled - $targetSku.ConsumedUnits");
  lines.push("if ($available -lt $DriftedUpns.Count) { Write-Warning \"Only $available $TargetSkuPartNumber seats available for $($DriftedUpns.Count) users\" }");
  lines.push("");
  lines.push("foreach ($upn in $DriftedUpns) {");
  lines.push("    $user = Get-MgUser -UserId $upn -Property Id,UserPrincipalName,UsageLocation,AssignedLicenses");
  lines.push("    if (-not $user.UsageLocation) {");
  lines.push("        if ($PSCmdlet.ShouldProcess($upn, 'Set UsageLocation CH')) { Update-MgUser -UserId $user.Id -UsageLocation 'CH' }");
  lines.push("    }");
  lines.push("    $remove = @()");
  lines.push("    if ($legacySku -and ($user.AssignedLicenses.SkuId -contains $legacySku.SkuId)) { $remove += $legacySku.SkuId }");
  lines.push("    if ($PSCmdlet.ShouldProcess($upn, \"Set-MgUserLicense +$TargetSkuPartNumber -$LegacySkuPartNumber\")) {");
  lines.push("        Set-MgUserLicense -UserId $user.Id -AddLicenses @(@{ SkuId = $targetSku.SkuId }) -RemoveLicenses $remove | Out-Null");
  lines.push("        Write-Host \"[OK] $upn -> $TargetSkuPartNumber\" -ForegroundColor Green");
  lines.push("    }");
  lines.push("}");
  if (blocking) {
    lines.push("");
    lines.push("# --- 2. Conditional Access remediation (Update-MgIdentityConditionalAccessPolicy) ---");
    lines.push("$group = Get-MgGroup -Filter \"displayName eq '$EntitlementGroupName'\" -Top 1");
    lines.push("if (-not $group) { throw \"Group $EntitlementGroupName not found\" }");
    lines.push("$policy = Get-MgIdentityConditionalAccessPolicy -All | Where-Object DisplayName -eq $PolicyDisplayName | Select-Object -First 1");
    lines.push("if (-not $policy) { throw \"Conditional Access policy '$PolicyDisplayName' not found\" }");
    lines.push("$excludeGroups = @($policy.Conditions.Users.ExcludeGroups) + $group.Id | Select-Object -Unique");
    lines.push("$body = @{");
    lines.push("    state      = 'enabledForReportingButNotEnforced'");
    lines.push("    conditions = @{ users = @{ excludeGroups = @($excludeGroups) } }");
    lines.push("}");
    lines.push("if ($PSCmdlet.ShouldProcess($PolicyDisplayName, \"Exclude $EntitlementGroupName and switch to report-only\")) {");
    lines.push("    Update-MgIdentityConditionalAccessPolicy -ConditionalAccessPolicyId $policy.Id -BodyParameter $body");
    lines.push("    Write-Host \"[OK] $PolicyDisplayName -> report-only, excluded $EntitlementGroupName\" -ForegroundColor Green");
    lines.push("}");
  }
  lines.push("");
  lines.push(`Write-Host 'ContextPane remediation ${ticket} complete.' -ForegroundColor Cyan`);
  return lines.join("\n") + "\n";
}

export function buildRemediationBundle(ctx: CorrelationContext): RemediationBundleArgs {
  const lic = ctx.license.data;
  const d = ctx.drift.data;
  const blocking = ctx.policies.data.find((p) => p.blocks) ?? ctx.policies.data[0];
  const rogueNames = d.rogueSecurityRules.map((r) => r.ruleName);
  const tagFixes = d.tagDrift.filter((t) => t.expectedInTf !== null).map((t) => `${t.key} = "${t.expectedInTf}"`);
  const summaryParts = [
    `Assigns ${lic.sku.skuPartNumber} to ${lic.driftedUsers.length} drifted member(s) of ${lic.group.displayName} and removes ${lic.sku.legacySkuPartNumber}.`,
    blocking ? `Excludes ${lic.group.displayName} from '${blocking.displayName}' and switches it to report-only.` : "",
    rogueNames.length ? `Removes rogue NSG rule(s) ${rogueNames.join(", ")} from ${d.resourceName}` : "",
    tagFixes.length ? `${rogueNames.length ? "and restores" : "Restores"} tag(s) ${tagFixes.join(", ")}.` : rogueNames.length ? "." : "",
  ].filter(Boolean);
  return {
    title: `Fix ${ctx.erp.ticket.ticketId}: license drift, CA block and NSG drift for ${ctx.erp.tenant.displayName}`,
    summary: summaryParts.join(" ").slice(0, 600),
    powershellScript: buildPowerShellRemediation(ctx),
    terraformDiff: d.hclDiff,
    affectedEntities: [
      ...lic.driftedUsers.map((u) => ({ type: "upn" as const, id: u.upn, change: `${u.currentSku} → ${u.expectedSku}` })),
      ...(blocking ? [{ type: "policy" as const, id: blocking.id, change: `exclude ${lic.group.displayName}; state → report-only` }] : []),
      ...d.rogueSecurityRules.map((r) => ({ type: "resource" as const, id: `${d.resourceName}/${r.ruleName}`, change: `remove rule (priority ${r.priority}, ${r.protocol} ${r.port} from ${r.source})` })),
      ...d.tagDrift.map((t) => ({ type: "resource" as const, id: `${d.resourceName}/tags/${t.key}`, change: `${t.actualInAzure ?? "∅"} → ${t.expectedInTf ?? "∅"}` })),
    ].slice(0, 20),
    riskNotes: [
      "License assignment requires available seats; the script warns if the pool is short.",
      blocking ? "Report-only keeps the policy observable in sign-in logs without enforcing the block." : "",
      rogueNames.length ? "Removing the temporary RDP/SSH rule may interrupt any vendor session still using it." : "",
      "Terraform apply will reconcile Azure to the baseline; review the plan in the staged PR first.",
    ].filter(Boolean).slice(0, 6),
  };
}
