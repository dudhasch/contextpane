export function buildRemediationPlan(ctx: CorrelationContext): RemediationPlan {
  switch (ctx.scenarioId) {
    case "INC-4092":
      return contosoTicket(ctx);
    case "ANOM-LIC-101":
      return licenseAnomaly(ctx);
    case "ANOM-CA-204":
      return caAnomaly(ctx);
    case "INC-4099":
    case "ANOM-INT-309":
      return intuneFix(ctx);
  }
}

/** Back-compat for callers that only need the bundle. */
export function buildRemediationBundle(ctx: CorrelationContext): RemediationBundleArgs {
  return buildRemediationPlan(ctx).bundle;
}
