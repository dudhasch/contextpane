/* ANOM-CA-204 · break-glass exclusion, enforce legacy-auth block              */
/* -------------------------------------------------------------------------- */

function caAnomaly(ctx: CorrelationContext): RemediationPlan {
  const posture = ctx.caPosture!.data;
  const [ca001, ca004] = [CA_POSTURE.policies[0]!, CA_POSTURE.policies[1]!];
  const L: string[] = [
    ...header(ctx, ["Microsoft.Graph.Groups", "Microsoft.Graph.Identity.SignIns"], "restore break-glass exclusion, enforce legacy-auth block", [
      `1. Add ${CA_POSTURE.breakGlassGroup} back to the exclusions of '${ca001.displayName}'.`,
      `2. Switch '${ca004.displayName}' from enabledForReportingButNotEnforced to enabled.`,
      "   Both policies then match the golden baseline in Git.",
    ]),
    "param(",
    `    [string]$TenantId = ${ps(ctx.erp.tenant.entraTenantId)},`,
    `    [string]$BreakGlassGroupName = ${ps(CA_POSTURE.breakGlassGroup)},`,
    `    [string]$AdminMfaPolicyName = ${ps(ca001.displayName)},`,
    `    [string]$LegacyAuthPolicyName = ${ps(ca004.displayName)}`,
    ")",
    "",
    ...connectGuard(["Policy.Read.All", "Policy.ReadWrite.ConditionalAccess", "Group.Read.All"]),
    `$breakGlass = Get-MgGroup -Filter "displayName eq '$BreakGlassGroupName'" -Top 1`,
    'if (-not $breakGlass) { throw "Group $BreakGlassGroupName not found" }',
    "$policies = Get-MgIdentityConditionalAccessPolicy -All",
    "",
    "# --- 1. Restore the break-glass exclusion on CA-001 ------------------------------",
    "$admin = $policies | Where-Object DisplayName -eq $AdminMfaPolicyName | Select-Object -First 1",
    `if (-not $admin) { throw "Conditional Access policy '$AdminMfaPolicyName' not found" }`,
    "if ($admin.Conditions.Users.ExcludeGroups -notcontains $breakGlass.Id) {",
    "    $exclude = @($admin.Conditions.Users.ExcludeGroups) + $breakGlass.Id | Select-Object -Unique",
    "    $body = @{ conditions = @{ users = @{ includeGroups = @($admin.Conditions.Users.IncludeGroups); excludeGroups = @($exclude) } } }",
    '    if ($PSCmdlet.ShouldProcess($AdminMfaPolicyName, "Exclude $BreakGlassGroupName")) {',
    "        Update-MgIdentityConditionalAccessPolicy -ConditionalAccessPolicyId $admin.Id -BodyParameter $body",
    '        Write-Host "[OK] $AdminMfaPolicyName excludes $BreakGlassGroupName" -ForegroundColor Green',
    "    }",
    "}",
    "",
    "# --- 2. Enforce the legacy-auth block (CA-004) ---------------------------------",
    "$legacy = $policies | Where-Object DisplayName -eq $LegacyAuthPolicyName | Select-Object -First 1",
    `if (-not $legacy) { throw "Conditional Access policy '$LegacyAuthPolicyName' not found" }`,
    "if ($legacy.State -ne 'enabled') {",
    "    if ($PSCmdlet.ShouldProcess($LegacyAuthPolicyName, \"State $($legacy.State) -> enabled\")) {",
    "        Update-MgIdentityConditionalAccessPolicy -ConditionalAccessPolicyId $legacy.Id -BodyParameter @{ state = 'enabled' }",
    '        Write-Host "[OK] $LegacyAuthPolicyName enforced" -ForegroundColor Green',
    "    }",
    "}",
  ];
  const live001 = posture.policies.find((p) => p.displayName === ca001.displayName);
  const live004 = posture.policies.find((p) => p.displayName === ca004.displayName);
  return {
    bundle: {
      title: `Fix ${ctx.ticketId}: restore break-glass exclusion and enforce the legacy-auth block`,
      summary: `Adds ${CA_POSTURE.breakGlassGroup} back to the exclusions of ${short(ca001.displayName)} (break-glass lockout risk) and switches ${short(ca004.displayName)} from Report-Only to enabled, which stops the ${posture.legacySignIns.length} legacy IMAP/SMTP sign-ins seen in 24 h.`.slice(0, 600),
      powershellScript: `${L.join("\n")}\n`,
      terraformDiff: "",
      graphPatch: graphPatch([
        { method: "PATCH", url: `/identity/conditionalAccess/policies/${live001?.id ?? "ca-policy-001"}`, body: { conditions: { users: { excludeGroups: [GROUP_IDS[CA_POSTURE.breakGlassGroup] ?? "sg-breakglass-accounts-01"] } } } },
        { method: "PATCH", url: `/identity/conditionalAccess/policies/${live004?.id ?? "ca-policy-004"}`, body: { state: "enabled" } },
      ]),
      affectedEntities: [
        { type: "policy", id: live001?.id ?? ca001.displayName, change: `excludeGroups += ${CA_POSTURE.breakGlassGroup}` },
        { type: "policy", id: live004?.id ?? ca004.displayName, change: "state: enabledForReportingButNotEnforced → enabled" },
        { type: "group", id: CA_POSTURE.breakGlassGroup, change: "excluded from CA-001 again" },
      ],
      riskNotes: [
        "Enforcing CA-004 blocks every IMAP4 / SMTP AUTH client of the scoped users; confirm no scanner or app relies on them.",
        "Check bg-admin-01 can still sign in after the change (break-glass test).",
      ],
    },
    requiredCommands: ["update-mgidentityconditionalaccesspolicy"],
    remediatedUpns: [],
    reclaimedUpns: [],
  };
}

