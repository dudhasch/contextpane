function licenseAnomaly(ctx: CorrelationContext): RemediationPlan {
  const inv = ctx.license!.data;
  const orphaned = inv.users.filter((u) => u.assignmentState === "Orphaned");
  const failed = inv.users.filter((u) => u.assignmentState === "Error: CountViolation");
  const reclaimSkus = [...new Set(orphaned.flatMap((u) => u.currentSku.split(",").map((s) => s.trim())))].filter((s) => s && s !== "NONE");
  const L: string[] = [
    ...header(ctx, ["Microsoft.Graph.Users", "Microsoft.Graph.Groups", "Microsoft.Graph.Identity.DirectoryManagement"], "reclaim orphaned seats, resolve CountViolation", [
      `1. Remove ${reclaimSkus.join(", ") || "SPE_E5"} from ${orphaned.length} disabled account(s) (direct assignments) and drop them from ${inv.groupName}.`,
      `2. Reprocess group-based licensing for ${failed.length} CountViolation member(s) (Invoke-MgLicenseUser).`,
      "   No new licenses are purchased: the reclaimed seats cover the failed assignments.",
    ]),
    "param(",
    `    [string]$TenantId = ${ps(ctx.erp.tenant.entraTenantId)},`,
    `    [string]$LicensingGroupName = ${ps(inv.groupName)},`,
    `    [string]$SkuPartNumber = ${ps(inv.sku.skuPartNumber)},`,
    `    [string[]]$ReclaimSkuPartNumbers = @(${(reclaimSkus.length ? reclaimSkus : [inv.sku.skuPartNumber]).map(ps).join(", ")}),`,
    `    [string[]]$DisabledUpns = @(${orphaned.map((u) => ps(u.upn)).join(", ")}),`,
    `    [string[]]$CountViolationUpns = @(${failed.map((u) => ps(u.upn)).join(", ")})`,
    ")",
    "",
    ...connectGuard(["User.ReadWrite.All", "Group.ReadWrite.All", "Organization.Read.All", "LicenseAssignment.ReadWrite.All"]),
    "$skus = Get-MgSubscribedSku -All",
    "$reclaim = @($skus | Where-Object SkuPartNumber -in $ReclaimSkuPartNumbers)",
    `$group = Get-MgGroup -Filter "displayName eq '$LicensingGroupName'" -Top 1`,
    'if (-not $group) { throw "Group $LicensingGroupName not found" }',
    "",
    "# --- 1. Reclaim seats from disabled accounts (Set-MgUserLicense, Remove-MgGroupMemberByRef) ---",
    "foreach ($upn in $DisabledUpns) {",
    "    $user = Get-MgUser -UserId $upn -Property Id,AccountEnabled,LicenseAssignmentStates",
    '    if ($user.AccountEnabled) { Write-Warning "$upn is enabled again; skipped"; continue }',
    "    $direct = @($user.LicenseAssignmentStates | Where-Object { -not $_.AssignedByGroup -and $_.SkuId -in $reclaim.SkuId } | ForEach-Object SkuId | Select-Object -Unique)",
    "    if ($direct.Count -gt 0) {",
    '        if ($PSCmdlet.ShouldProcess($upn, "Set-MgUserLicense -RemoveLicenses $($ReclaimSkuPartNumbers -join \', \')")) {',
    "            Set-MgUserLicense -UserId $user.Id -AddLicenses @() -RemoveLicenses $direct | Out-Null",
    "        }",
    "    }",
    '    if ($PSCmdlet.ShouldProcess($upn, "Remove-MgGroupMemberByRef from $LicensingGroupName (group-based path)")) {',
    "        Remove-MgGroupMemberByRef -GroupId $group.Id -DirectoryObjectId $user.Id",
    '        Write-Host "[OK] $upn reclaimed" -ForegroundColor Green',
    "    }",
    "}",
    "",
    "# --- 2. Reprocess group-based licensing for the CountViolation members ---------",
    "foreach ($upn in $CountViolationUpns) {",
    "    $user = Get-MgUser -UserId $upn -Property Id",
    "    if ($PSCmdlet.ShouldProcess($upn, 'Invoke-MgLicenseUser (reprocess group licensing)')) {",
    "        Invoke-MgLicenseUser -UserId $user.Id | Out-Null",
    '        Write-Host "[OK] $upn reprocessed" -ForegroundColor Green',
    "    }",
    "}",
    "",
    "$pool = Get-MgSubscribedSku -All | Where-Object SkuPartNumber -eq $SkuPartNumber",
    'Write-Host ("{0}: {1}/{2} consumed after reclaim" -f $SkuPartNumber, $pool.ConsumedUnits, $pool.PrepaidUnits.Enabled) -ForegroundColor Cyan',
  ];
  return {
    bundle: {
      title: `Fix ${ctx.ticketId}: reclaim ${orphaned.length} orphaned seats and resolve CountViolation on ${inv.groupName}`,
      summary: `Removes ${reclaimSkus.join(" and ") || inv.sku.skuPartNumber} from ${orphaned.length} disabled accounts (Direct + Group paths) and reprocesses group-based licensing so ${failed.length} CountViolation member(s) of ${inv.groupName} resolve to Active with 0 new license purchases.`.slice(0, 600),
      powershellScript: `${L.join("\n")}\n`,
      terraformDiff: "",
      graphPatch: graphPatch([
        ...orphaned.map((u, idx) => ({ method: "POST", url: `/v1.0/users/${userUuid(u.objectId ?? u.upn, idx + 1)}/assignLicense`, body: { addLicenses: [], removeLicenses: reclaimSkus.map((s) => SKU_GUIDS[s] ?? "06ebc4ee-1bb5-47dd-8120-11324bc54e06") } })),
        ...orphaned.map((u, idx) => ({ method: "DELETE", url: `/v1.0/groups/${GROUP_IDS[inv.groupName] ?? "c3d4e5f6-a7b8-4c5d-9e0f-1a2b3c4d5e6f"}/members/${userUuid(u.objectId ?? u.upn, idx + 1)}/$ref` })),
        ...failed.map((u, idx) => ({ method: "POST", url: `/v1.0/users/${userUuid(u.objectId ?? u.upn, idx + 10)}/reprocessLicenseAssignment`, body: {} })),
      ]),
      affectedEntities: [
        ...orphaned.map((u) => ({ type: "upn" as const, id: u.upn, change: `reclaim ${u.currentSku}; remove from ${inv.groupName}` })),
        ...failed.map((u) => ({ type: "upn" as const, id: u.upn, change: `CountViolation → Active (${inv.sku.skuPartNumber})` })),
        { type: "group" as const, id: inv.groupName, change: "licensing errors 1 → 0" },
      ].slice(0, 20),
      riskNotes: [
        "Only accounts with accountEnabled = false are touched; a re-enabled account is skipped with a warning.",
        "Mailbox data of the disabled accounts is unaffected; Exchange retention applies as before.",
      ],
    },
    requiredCommands: ["set-mguserlicense", "invoke-mglicenseuser"],
    remediatedUpns: failed.map((u) => u.upn),
    reclaimedUpns: orphaned.map((u) => u.upn),
  };
}

