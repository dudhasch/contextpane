/**
 * Deterministic remediation templates, one per scenario. These are what Tier 3
 * falls back to without a Meta API key, and the reference the muse-code output is
 * checked against (same cmdlets, same entities). Every mutating call sits inside
 * $PSCmdlet.ShouldProcess, so -WhatIf is a real dry run.
 */

export interface RemediationPlan {
  bundle: RemediationBundleArgs;
  /** Cmdlets the pre-flight requires in the script (lower-case). */
  requiredCommands: string[];
  /** Users whose license assignment the fix activates (canvas convergence). */
  remediatedUpns: string[];
  /** Disabled accounts whose seats the fix reclaims. */
  reclaimedUpns: string[];
}

function ps(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

const short = (name: string) => name.replace("[ContextPane-Demo] ", "");

function header(ctx: CorrelationContext, modules: string[], synopsis: string, description: string[]): string[] {
  return [
    "#Requires -Version 7.0",
    `#Requires -Modules ${modules.join(", ")}`,
    "<#",
    ".SYNOPSIS",
    `    ContextPane remediation for ${ctx.ticketId}: ${synopsis}`,
    ".DESCRIPTION",
    ...description.map((d) => `    ${d}`),
    "    Generated by ContextPane Tier 3 for human approval. Run with -WhatIf first.",
    "#>",
    "[CmdletBinding(SupportsShouldProcess)]",
  ];
}

function connectGuard(scopes: string[]): string[] {
  return [
    "$ErrorActionPreference = 'Stop'",
    "",
    "$ctx = Get-MgContext",
    `if (-not $ctx) { throw 'No Microsoft Graph context. Run Connect-MgGraph -TenantId $TenantId -Scopes ${scopes.join(",")}' }`,
    'if ($ctx.TenantId -ne $TenantId) { throw "Connected to tenant $($ctx.TenantId), expected $TenantId" }',
    "",
  ];
}

const graphPatch = (requests: Array<{ method: string; url: string; body?: unknown; note?: string }>) => `${JSON.stringify(requests, null, 2)}\n`;

